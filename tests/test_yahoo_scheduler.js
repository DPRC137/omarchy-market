const assert = require('node:assert/strict');
const Queue = require('./load_model')('RequestQueue');
let now = 1000;
const started = [], callbacks = [];
let concurrent = 0, maxConcurrent = 0;
const q = Queue.create((request, done) => {
  concurrent++; maxConcurrent = Math.max(concurrent, maxConcurrent);
  const job = { request, done(result) { concurrent--; done(result); }, aborted: false };
  started.push(job);
  return () => { job.aborted = true; concurrent = Math.max(0, concurrent - 1); };
}, () => now, 1200, 3);
const submit = (key, priority = 10) => q.enqueue({ key, priority }, r => callbacks.push([key, r]));
assert.equal(submit('quote:AAPL'), true);
assert.equal(submit('quote:AAPL'), false);
submit('quote:MSFT'); submit('quote:NVDA'); submit('history:AAPL', 100);
assert.equal(started.length, 1);
started[0].done({ data: {} });
q.pump(); assert.equal(started.length, 1);
now += 1200; q.pump(); assert.equal(started[1].request.key, 'history:AAPL');
assert.equal(maxConcurrent, 1);
started[1].done({ error: 'HTTP 429', retryable: true });
now += 3999; q.pump(); assert.equal(started.length, 2);
now++; q.pump(); assert.equal(started[2].request.key, 'history:AAPL');
// Deadline drives a retry and abort even if transport emits nothing (QML XHR).
now += 8000; q.pump(); assert.equal(started[2].aborted, true);
const count = callbacks.length;
started[2].done({ data: 'late' }); assert.equal(callbacks.length, count);
now += 8000; q.pump();
started[2].done({ data: "late previous attempt" });
assert.equal(q.active.request.key, "history:AAPL");
started[3].done({ error: 'HTTP 500', retryable: true });
assert.equal(callbacks.filter(([k]) => k === 'history:AAPL').length, 1); // finite retries
now += 1200; q.pump();
q.cancel(r => r.key === 'quote:MSFT');
assert.equal(started[4].aborted, true);
assert.equal(callbacks.find(([k]) => k === 'quote:MSFT')[1].cancelled, true);
q.stop();
assert.equal(q.hasWork(), false);
assert.equal(submit('after-stop'), false);
// Bounded queue never drops the newest visible request without notification.
const bound = Queue.create(() => () => {}, () => now, 0, 2);
const evicted = [];
bound.enqueue({ key: 'active' }, () => {});
bound.enqueue({ key: 'low1', priority: 1 }, r => evicted.push(r));
bound.enqueue({ key: 'low2', priority: 1 }, r => evicted.push(r));
bound.enqueue({ key: 'visible', priority: 100 }, () => {});
assert.equal(bound.pending.length, 2);
assert.equal(bound.pending[0].request.key, 'visible');
assert.equal(evicted.length, 1);
console.log('PASS production queue: serialization, priority, dedupe, bounds, backoff, Qt deadlines, late callbacks, cancellation and shutdown');
