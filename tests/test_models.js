const assert = require('node:assert/strict');
const fs = require('node:fs');
const M = require('./load_model')('MarketModel');
const fixture = name => JSON.parse(fs.readFileSync(`${__dirname}/fixtures/${name}.json`));
const now = 1787262066020;
const b = M.normalizeBinanceTicker(fixture('binance_btc').data, now);
const c = M.normalizeCoinbaseTicker(fixture('coinbase_btc'), now);
const hl = M.normalizeHyperliquidMeta(fixture('hyperliquid_meta'), ['BTC', 'HYPE'], now);
assert.equal(b.price, 72806);
assert.equal(b.currency, 'USDT');
assert.equal(b.instrument, 'BTC_USDT_SPOT');
assert.equal(b.volumeUnit, 'USDT');
assert.equal(c.currency, 'USD');
assert.equal(c.volumeUnit, 'BTC');
assert.equal(hl[1].priceType, 'PERP_MARK');
assert.equal(hl[1].high24h, null);
assert.equal(M.calculateReferenceQuote('BTC', { binance: b, coinbase: c }, now).price, b.price);
assert.equal(M.calculateReferenceQuote('BTC', { coinbase: c, hyperliquid: hl[0] }, now).price, null);
assert.equal(M.calculateReferenceQuote('HYPE', { hyperliquid: hl[1] }, now).instrument, 'HYPE_USD_PERP');
assert.equal(M.calculateReferenceQuote('BTC', { binance: b }, now + 16000).freshness, 'STALE');
assert.equal(M.calculateReferenceQuote('BTC', { binance: b }, now + 600000).price, b.price);
assert.equal(M.calculateReferenceQuote('BTC', { binance: b }, now + 600000).freshness, 'STALE');
assert.equal(M.calculateReferenceQuote('BTC', { binance: { ...b, receivedTimestamp: now + 600001 } }, now + 600001).freshness, 'LIVE');
const rest = M.normalizeBinanceTicker({ symbol: 'BTCUSDT', lastPrice: '123', quoteVolume: '456', priceChangePercent: '2', closeTime: now }, now);
assert.equal(rest.price, 123);
assert.equal(M.normalizeBinanceTicker({ s: 'BTCUSD', c: '123' }), null);
assert.equal(M.normalizeCoinbaseTicker({ product_id: 'BTC-EUR', price: '123' }), null);
assert.equal(rest.volume24h, 456);
assert.equal(M.normalizeBinanceTicker({ s: 'BTCUSDT', c: 'NaN' }), null);
assert.equal(M.normalizeBinanceTicker({ s: 'BTCUSDT', c: '123' }).change24h, null);
assert.equal(M.normalizeCoinbaseTicker({ product_id: 'BTC-USD', price: '123' }).change24h, null);
assert.equal(M.formatPrice(null), '—');
assert.equal(M.formatPercentage(null), '—');
assert.equal(M.formatVolume(null, 'shares'), '—');
assert.equal(M.formatVolume(1200, 'shares'), '1.2K shares');
assert.equal(M.formatVolume(0, 'shares'), '0 shares');
assert.equal(M.formatPrice(123, 2, 'INR'), 'INR 123.00');
assert.equal(M.formatPrice(123, 2, 'GBp'), 'GBp 123.00');
assert.equal(M.formatPrice(123, 2, 'USDT'), 'USDT 123.00');
const yahoo = fixture('yahoo_aapl');
yahoo.chart.result[0].meta.currency = 'USD';
const y = M.normalizeYahooChart(yahoo, now);
assert.ok(y.price > 0);
assert.equal(y.volumeUnit, 'shares');
const international = M.registerDynamicInstrument({ asset: 'RELIANCE.NS', currency: 'INR', name: 'Reliance' });
yahoo.chart.result[0].meta.symbol = 'RELIANCE.NS';
yahoo.chart.result[0].meta.currency = 'INR';
const india = M.normalizeYahooChart(yahoo, now);
assert.equal(india.currency, 'INR');
assert.equal(india.instrument, 'RELIANCE.NS_INR_STOCK');
yahoo.chart.result[0].meta.currency = '';
assert.equal(M.normalizeYahooChart(yahoo, now), null);
let w = M.createDefaultWatchlist();
w = M.addWatchlistMarket(w, international).watchlist;
w = M.reorderWatchlistMarket(w, w.items.length - 1, 0).watchlist;
M.clearDynamicInstruments();
const restored = M.deserializeWatchlist(M.serializeWatchlist(w));
assert.equal(restored.version, 2);
assert.deepEqual(restored.items.map(i => i.asset), w.items.map(i => i.asset));
assert.equal(restored.items[0].currency, 'INR');
assert.equal(M.getCatalogItem('RELIANCE.NS').currency, 'INR');
assert.deepEqual(M.deserializeWatchlist('["ETH","BTC","AAPL"]').items.map(i => i.asset), ['ETH', 'BTC', 'AAPL']);
const legacy = M.deserializeWatchlist('{"version":1,"items":[{"asset":"VOD.L","assetClass":"stock","instrument":"VOD.L_USD_STOCK"}]}');
assert.equal(legacy.items[0].asset, 'VOD.L');
assert.equal(legacy.items[0].currency, null);
assert.equal(M.canonicalizeDynamicStock({ asset: 'BAD/URL' }), null);
const warn = console.warn;
console.warn = () => {};
assert.equal(M.deserializeWatchlist('broken').items.length, 4);
console.warn = warn;
console.log('PASS production model: source isolation, time-based freshness, recovery, units, nulls, international metadata and ordered migration');
