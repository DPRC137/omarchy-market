'use strict';
const assert = require('node:assert/strict');
const load = require('./load_model');
const view = load('WatchlistView');
const model = load('MarketModel');
const assets = ['BTC', 'MSFT', 'ETH', 'AAPL'];
const values = { BTC: -1, MSFT: 4, ETH: null, AAPL: 2 };
const quote = asset => ({change24h: values[asset]});
const project = (query = '', category = 'All', sort = 'Watchlist') => view.project(assets, query, category, sort, model.getCatalogItem, quote);
assert.deepEqual(project(' apple '), ['AAPL']);
assert.deepEqual(project('', 'Crypto'), ['BTC', 'ETH']);
assert.deepEqual(project('', 'Stocks & ETFs'), ['MSFT', 'AAPL']);
assert.deepEqual(project('', 'All', 'Symbol'), ['AAPL', 'BTC', 'ETH', 'MSFT']);
assert.deepEqual(project('', 'All', 'Gainers'), ['MSFT', 'AAPL', 'BTC', 'ETH']);
assert.deepEqual(project('', 'All', 'Losers'), ['BTC', 'AAPL', 'MSFT', 'ETH']);
assert.deepEqual(project('no such asset'), []);
assert.deepEqual(assets, ['BTC', 'MSFT', 'ETH', 'AAPL']);
assert.deepEqual(view.project([], '', 'All', 'Gainers', model.getCatalogItem, quote), []);
console.log('Watchlist projection: PASS');
