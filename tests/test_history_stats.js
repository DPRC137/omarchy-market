'use strict';
const assert = require('node:assert/strict');
const stats = require('./load_model')('HistoryStats');
const p = (day, close) => ({time: Date.UTC(2026, 9, day), close});
const empty = stats.summarize([]);
assert.equal(empty.count, 0);
for (const key of ['firstTime','lastTime','first','last','high','low','mean','change','changePercent']) assert.equal(empty[key], null);
const one = stats.summarize([p(1, 100)]);
assert.equal(one.high, 100); assert.equal(one.low, 100); assert.equal(one.mean, 100);
assert.equal(one.change, null); assert.equal(one.changePercent, null);
const data = [p(5, 120), p(1, 100), p(2, 80)];
const copy = JSON.stringify(data);
assert.deepEqual(stats.summarize(data), {count:3,firstTime:p(1,100).time,lastTime:p(5,120).time,first:100,last:120,high:120,low:80,mean:100,change:20,changePercent:20});
assert.equal(JSON.stringify(data), copy, 'Do not sort or mutate cached history');
const down = stats.summarize([p(1, 200), p(2, 150)]);
assert.equal(down.change, -50); assert.equal(down.changePercent, -25);
const flat = stats.summarize([p(1, 2), p(2, 2)]);
assert.equal(flat.change, 0); assert.equal(flat.changePercent, 0);
const invalid = [null, {}, p(1,null), p(1,0), p(1,-1), p(1,'100'), p(1,Infinity), {time:NaN,close:100}, {time:0,close:100}];
assert.equal(stats.summarize(invalid).count, 0);
const duplicate = stats.summarize([p(1,100),p(1,999),p(4,110)]);
assert.equal(duplicate.count, 2); assert.equal(duplicate.mean, 105);
const closed = stats.summarize([p(2,100),p(5,110)]);
assert.equal(closed.count,2); assert.equal(closed.changePercent,10, 'Closures add no inferred observations');
const huge = stats.summarize([p(1,1e308),p(2,1.1e308)]);
assert.ok(Number.isFinite(huge.mean));
assert.equal(stats.summarize([p(1,1e-300),p(2,1e300)]).changePercent, null);
console.log('PASS history window stats: observed closes, ordering, nulls, single/flat/down windows, no mutation or fabricated intervals');
