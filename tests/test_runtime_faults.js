const assert = require('node:assert/strict');
const M = require('./load_model')('MarketModel');
const periods = { pre: { start: 1000, end: 2000 }, regular: { start: 2000, end: 5000 }, post: { start: 5000, end: 7000 } };
const payload = { chart: { result: [{ meta: { symbol: 'AAPL', currency: 'USD', regularMarketPrice: 300, regularMarketTime: 4000, previousClose: 295, currentTradingPeriod: periods }, timestamp: [1000, 2000, 3000, 5000], indicators: { quote: [{ close: [400, 300, 300, 500], high: [401, 302, 303, 501], low: [399, 298, 299, 499], volume: [100, 200, 300, 100] }] } }] } };
const quote = M.normalizeYahooChart(payload, 3500000);
assert.equal(quote.price, 300);
assert.equal(quote.high24h, 303);
assert.equal(quote.low24h, 298);
assert.equal(quote.volume24h, 500);
assert.equal(quote.previousClose, 295);
assert.equal(quote.marketState, 'regular');
assert.equal(M.decorateQuote(quote, 5100000).marketState, 'postMarket');
const closed = M.normalizeYahooChart(payload, 8000000);
assert.equal(closed.price, 300); // No postmarket substitution.
assert.equal(closed.previousClose, 295);
assert.equal(M.decorateQuote(closed, 8000000 + 300001).freshness, 'CURRENT');
assert.equal(M.decorateQuote(closed, 8000000 + 660001).freshness, 'STALE');
assert.equal(M.decorateQuote(closed, 8000000).marketState, 'closed');
assert.equal(M.decorateQuote(quote, 3500000 + 119999).freshness, 'CURRENT');
assert.equal(M.decorateQuote(quote, 3500000 + 120001).freshness, 'STALE');
for (const bad of [null, {}, { chart: {} }, { chart: { result: [] } }, { chart: { result: [null] } }]) assert.equal(M.normalizeYahooChart(bad), null);
const missing = { chart: { result: [{ meta: { symbol: 'AAPL', currency: 'USD', regularMarketPrice: 1 } }] } };
assert.equal(M.normalizeYahooChart(missing).high24h, null);
assert.equal(M.normalizeYahooChart(missing).volume24h, null);
assert.equal(M.normalizeYahooChart(missing).change24h, null);
assert.equal(M.normalizeYahooChart(missing).marketState, 'unknown');
console.log('PASS production session boundaries, closed-market freshness, null metrics and malformed responses');
